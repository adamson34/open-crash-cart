import Foundation

/// Translates macOS virtual key codes (Carbon `kVK_*`) to USB HID keyboard usage IDs
/// (HID Usage Tables, Keyboard/Keypad page 0x07). Built from the public USB-IF spec, not
/// from any vendor code.
///
/// The adapter tracks modifier state from modifier-key events themselves (usages
/// 0xE0–0xE7), so we send those like any other key and leave the modifier mask at 0 —
/// matching the device's expected behavior.
public enum HIDKeymap {

    /// macOS virtual key code → HID usage. Returns nil for keys we don't map.
    public static func hidUsage(forMacKeyCode keyCode: UInt16) -> UInt8? {
        table[keyCode]
    }

    /// True for the eight modifier usages (LeftControl…RightGUI).
    public static func isModifier(_ usage: UInt8) -> Bool {
        (0xE0...0xE7).contains(usage)
    }

    // kVK_* (left) → HID usage (right). Comprehensive ANSI + keypad + function + nav set.
    private static let table: [UInt16: UInt8] = [
        // Letters
        0x00: 0x04, 0x0B: 0x05, 0x08: 0x06, 0x02: 0x07, 0x0E: 0x08, 0x03: 0x09, // a b c d e f
        0x05: 0x0A, 0x04: 0x0B, 0x22: 0x0C, 0x26: 0x0D, 0x28: 0x0E, 0x25: 0x0F, // g h i j k l
        0x2E: 0x10, 0x2D: 0x11, 0x1F: 0x12, 0x23: 0x13, 0x0C: 0x14, 0x0F: 0x15, // m n o p q r
        0x01: 0x16, 0x11: 0x17, 0x20: 0x18, 0x09: 0x19, 0x0D: 0x1A, 0x07: 0x1B, // s t u v w x
        0x10: 0x1C, 0x06: 0x1D,                                                  // y z
        // Number row
        0x12: 0x1E, 0x13: 0x1F, 0x14: 0x20, 0x15: 0x21, 0x17: 0x22,             // 1 2 3 4 5
        0x16: 0x23, 0x1A: 0x24, 0x1C: 0x25, 0x19: 0x26, 0x1D: 0x27,             // 6 7 8 9 0
        // Whitespace / editing
        0x24: 0x28, 0x35: 0x29, 0x33: 0x2A, 0x30: 0x2B, 0x31: 0x2C,             // ret esc bksp tab space
        // Punctuation
        0x1B: 0x2D, 0x18: 0x2E, 0x21: 0x2F, 0x1E: 0x30, 0x2A: 0x31,             // - = [ ] \
        0x29: 0x33, 0x27: 0x34, 0x32: 0x35, 0x2B: 0x36, 0x2F: 0x37, 0x2C: 0x38, // ; ' ` , . /
        0x39: 0x39,                                                             // caps lock
        // Function keys
        0x7A: 0x3A, 0x78: 0x3B, 0x63: 0x3C, 0x76: 0x3D, 0x60: 0x3E, 0x61: 0x3F, // F1–F6
        0x62: 0x40, 0x64: 0x41, 0x65: 0x42, 0x6D: 0x43, 0x67: 0x44, 0x6F: 0x45, // F7–F12
        // Navigation cluster
        0x72: 0x49, 0x73: 0x4A, 0x74: 0x4B, 0x75: 0x4C, 0x77: 0x4D, 0x79: 0x4E, // ins home pgup del end pgdn
        0x7C: 0x4F, 0x7B: 0x50, 0x7D: 0x51, 0x7E: 0x52,                         // right left down up
        // Keypad
        0x47: 0x53, 0x4B: 0x54, 0x43: 0x55, 0x4E: 0x56, 0x45: 0x57, 0x4C: 0x58, // numlk / * - + enter
        0x53: 0x59, 0x54: 0x5A, 0x55: 0x5B, 0x56: 0x5C, 0x57: 0x5D,             // kp1–5
        0x58: 0x5E, 0x59: 0x5F, 0x5B: 0x60, 0x5C: 0x61, 0x52: 0x62, 0x41: 0x63, // kp6–9 kp0 kp.
        // Modifiers (sent as key events; device derives modifier state from these).
        // The macOS Command keys (0x37/0x36) are intentionally NOT mapped: ⌘ has no PC
        // equivalent and is used for Mac system shortcuts (screenshot, ⌘-Tab, Spotlight),
        // so forwarding it would leak those shortcuts to the target. A dedicated "send
        // Windows key" action can offer the GUI key explicitly if needed.
        0x3B: 0xE0, 0x38: 0xE1, 0x3A: 0xE2,                                     // lctrl lshift lalt
        0x3E: 0xE4, 0x3C: 0xE5, 0x3D: 0xE6,                                     // rctrl rshift ralt
    ]
}
