import OCCKit

func runGunzipTests(_ t: Harness) {
    t.section("gzip inflate (firmware decompression)")

    // gzip of the ASCII string "OpenCrashCart" (captured with `gzip -n`).
    let blob: [UInt8] = [
        0x1f, 0x8b, 0x08, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x03,
        0xf3, 0x2f, 0x48, 0xcd, 0x73, 0x2e, 0x4a, 0x2c, 0xce, 0x70,
        0x4e, 0x2c, 0x2a, 0x01, 0x00, 0x59, 0xd8, 0xe4, 0xd5, 0x0d,
        0x00, 0x00, 0x00,
    ]
    let out = (try? gunzip(blob)).map { String(decoding: $0, as: UTF8.self) }
    t.expect(out == "OpenCrashCart", "gunzip inflates a gzip blob to its original bytes")
}
